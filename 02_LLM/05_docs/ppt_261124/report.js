/** 본문 한 문단. */
function p(text, opt) {
  const o = opt || {};
  return new Paragraph({
    children: [new TextRun({ text, size: o.size || 22, bold: !!o.bold, italics: !!o.italic, color: o.color })],
    spacing: { after: o.after === undefined ? 120 : o.after, line: 276 },
    indent: o.indent ? { left: o.indent } : undefined,
    alignment: o.align,
  });
}

/** 여러 서식이 섞인 한 문단. runs = [{t, b}] */
function pr(runs, opt) {
  const o = opt || {};
  return new Paragraph({
    children: runs.map(r => new TextRun({ text: r.t, size: o.size || 22, bold: !!r.b, color: r.c })),
    spacing: { after: o.after === undefined ? 120 : o.after, line: 276 },
    indent: o.indent ? { left: o.indent } : undefined,
  });
}

/** 글머리 기호 항목. 리터럴 가운뎃점을 쓰지 않고 numbering 설정을 쓴다. */
function li(text, level) {
  return new Paragraph({
    numbering: { reference: 'dot', level: level || 0 },
    children: [new TextRun({ text, size: 22 })],
    spacing: { after: 80, line: 276 },
  });
}

function h1(text) {
  return new Paragraph({ heading: HeadingLevel.HEADING_1, children: [new TextRun({ text, size: 28, bold: true })] });
}
function h2(text) {
  return new Paragraph({ heading: HeadingLevel.HEADING_2, children: [new TextRun({ text, size: 24, bold: true })] });
}

/** 표. widths 는 DXA 배열이고 합이 CW 가 되어야 한다. */
function tbl(rows, widths) {
  return new Table({
    columnWidths: widths,
    width: { size: CW, type: WidthType.DXA },
    rows: rows.map((cells, ri) => new TableRow({
      tableHeader: ri === 0,
      children: cells.map((c, ci) => new TableCell({
        width: { size: widths[ci], type: WidthType.DXA },
        shading: ri === 0 ? { type: ShadingType.CLEAR, fill: 'E8EDF3' } : undefined,
        margins: { top: 60, bottom: 60, left: 100, right: 100 },
        children: [new Paragraph({
          children: [new TextRun({ text: String(c), size: 20, bold: ri === 0 })],
          spacing: { after: 0, line: 260 },
        })],
      })),
    })),
  });
}

