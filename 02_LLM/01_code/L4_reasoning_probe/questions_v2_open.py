# 조립 — 문항 하나하나가 고유 템플릿이다.
#
# questions_v2.py 의 파라메트릭 갈래는 한 템플릿에서 25개 변형이 나오므로
# 신뢰구간을 낼 때 25개를 한 덩어리로 묶어야 한다. 반면 이 파일의 문항들은
# 서로 다른 문제라 각자가 독립 클러스터다. 그래서 id 를 문항별로 준다.
# ──────────────────────────────────────────────────────────────────────────

_GROUPS = [("fermi", _FERMI), ("dilemma", _DILEMMA), ("counterfactual", _COUNTER)]

QUESTIONS_OPEN = []
FAMILIES_OPEN = []
ANSWERS_OPEN = []

for _kind, _items in _GROUPS:
    for _i, _q in enumerate(_items):
        QUESTIONS_OPEN.append(" ".join(_q.split()))   # 줄바꿈으로 생긴 공백 정리
        FAMILIES_OPEN.append(f"{_kind}_{_i:03d}")
        ANSWERS_OPEN.append(None)                     # 채점하지 않는다


def self_test():
    from collections import Counter
    bad = 0
    print(f"총 {len(QUESTIONS_OPEN)}문항 / 템플릿 {len(set(FAMILIES_OPEN))}개")
    for kind, items in _GROUPS:
        print(f"  {kind:16s} {len(items):3d}")

    dup = len(QUESTIONS_OPEN) - len(set(QUESTIONS_OPEN))
    print(f"중복 문항: {dup}")
    if dup:
        for q, c in Counter(QUESTIONS_OPEN).most_common():
            if c > 1:
                print(f"  겹침: {q[:60]}")
        bad += 1

    # 선택지 4개(A~D)가 다 있는지. 하나라도 빠지면 모델이 답할 글자가 없다.
    for q in QUESTIONS_OPEN:
        if not all(f"{c})" in q for c in "ABCD"):
            print(f"  선택지 누락: {q[:60]}")
            bad += 1

    # 도피 선택지 검사 — 있으면 모델이 추론을 일찍 끝낸다
    escape = ("판단 불가", "알 수 없", "경우에 따라", "모름")
    for q in QUESTIONS_OPEN:
        for e in escape:
            if e in q:
                print(f"  도피선택지 '{e}': {q[:60]}")
                bad += 1

    print("\n자체 검사 " + ("통과" if bad == 0 else f"실패 {bad}건"))
    return bad


if __name__ == "__main__":
    import sys
    sys.exit(1 if self_test() else 0)
